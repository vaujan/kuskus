const assert = require('node:assert/strict')
const { mkdtemp, readFile, rm } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const test = require('node:test')
require('./helpers/install-ts-require.cjs')()
const { LibraryService } = require('../src/main/library/library-service.ts')

test('reset onboarding forgets the active library across launches and preserves its notes', async (context) => {
  const root = await mkdtemp(join(tmpdir(), 'kuskus-dev-reset-'))
  context.after(() => rm(root, { recursive: true, force: true }))
  const settingsPath = join(root, 'settings.json')
  const service = new LibraryService(settingsPath)
  const created = await service.createIn(root, 'Vault')
  const note = await service.createNote({ markdown: '# Keep me', attachmentIds: [] })
  const notePath = join(created.library.path, note.relativePath)
  const original = await readFile(notePath, 'utf8')
  const unsubscribe = service.onVaultChanged(() => {})
  context.after(unsubscribe)

  await service.resetOnboarding()
  assert.equal((await service.getState()).status, 'none')
  assert.equal(service.vaultWatcher, null)
  const reopened = new LibraryService(settingsPath)
  await reopened.initialize()
  assert.equal((await reopened.getState()).status, 'none')
  assert.equal(await readFile(notePath, 'utf8'), original)
  assert.equal((await reopened.openAt(created.library.path)).status, 'ready')
})
